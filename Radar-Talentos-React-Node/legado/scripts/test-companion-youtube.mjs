import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const ctx=vm.createContext({URL,Map,Set});
vm.runInContext(fs.readFileSync('worker/curation.js','utf8')+fs.readFileSync('worker/coverage.js','utf8'),ctx);
vm.runInContext(`
globalThis.channel='UC'+'x'.repeat(22);
globalThis.anchor={nome:'Pessoa',personId:'verified-instagram:pessoa',rede:'Instagram',url:'https://instagram.com/pessoa/',contentLanguage:'pt',categoria:'Cantores',categorias:['Cantores']};
originalCuratedHistory=async()=>({rows:[anchor]});
historyRows=async()=>[{nome:'Pessoa Oficial',rede:'YouTube',channelId:channel,url:'https://www.youtube.com/channel/'+channel,data:'2026-10-24',seguidores:90000}];
globalThis.lang='unknown';languageIndex=async()=>({['YouTube|'+channel]:{language:lang}});
languageProfileKey=r=>r.rede==='YouTube'?'YouTube|'+channel:'Instagram|pessoa';
filterBlockedProfiles=async(b,r)=>r;
readAll=async(b,p)=>p==='ig-profiles/'?[{nome:'Pessoa',username:'pessoa',linkedYoutubeChannelId:channel}]:[];
suggestedBiographyTopics=()=>[];countryPersonKey=s=>s;
globalThis.env={BUCKET:{}};
`,ctx);
let result=await vm.runInContext('curatedHistory(env)',ctx);
assert.equal(result.rows.length,2);
assert.equal(result.rows[1].rede,'YouTube');
assert.equal(result.rows[1].data,'2026-10-24');
assert.equal(result.rows[1].languageExempt,true);
assert.equal(result.rows[1].seguidores,90000);
assert.equal(result.rows[1].personId,result.rows[0].personId);
assert.equal(result.rows[1].collectionState,'collected');
vm.runInContext("lang='en'",ctx);
result=await vm.runInContext('curatedHistory(env)',ctx);
assert.equal(result.rows.length,1,'Confirmed foreign-language channels stay excluded');
console.log('Confirmed YouTube companion uses saved real count; foreign content stays excluded');

vm.runInContext(`lang='unknown';readAll=async(b,p)=>p==='youtube-instagram-links/'?[{links:[{username:'pessoa',youtubeChannelId:channel}]}]:[];anchor.personId='youtube:'+channel;`,ctx);
result=await vm.runInContext('curatedHistory(env)',ctx);
assert.equal(result.rows.filter(r=>r.rede==='YouTube').length,1,'Official saved links restore a pending-language channel even before registry enrichment');
console.log('Saved official association restores YouTube history without registry backfill');
