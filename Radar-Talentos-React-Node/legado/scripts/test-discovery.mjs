import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';

const files=['worker/profile-blocks.js','worker/taxonomy.js','worker/topic-discovery.js','worker/api.js','worker/instagram-sources.js','worker/coverage.js'];
const code=files.map(p=>fs.readFileSync(p,'utf8').replace(/export /g,'')).join('\n');
const records=new Map();
const bucket={async get(k){return records.has(k)?{json:async()=>structuredClone(records.get(k))}:null},async put(k,v){records.set(k,JSON.parse(v))}};
const ctx=vm.createContext({console,URL,Response,AbortSignal,TextDecoder,TextEncoder,Date,Set,Map,fetch:async()=>{throw Error('Unexpected network request')}});
vm.runInContext(code+`;chooseDiscoveryTopic=async()=>null;globalThis.subject={growBase,sourceHtml,scanSources,countryPersonKey};`,ctx);
ctx.bucket=bucket;
const id='UC'+'z'.repeat(22);
ctx.newId=id;
vm.runInContext(`ensureHistory=async()=>{};saveDay=async()=>{};readAll=async()=>Array.from({length:200},(_,i)=>({id:'old'+i,selector:{id:'old'+i},categoria:'Cantores'}));globalThis.params=[];youtubeFetch=async(env,resource,p)=>{params.push(p);return resource==='search'?{items:[{id:{channelId:newId}}],nextPageToken:'page-two'}:{items:[{id:newId,snippet:{title:'Cantor Teste'},statistics:{subscriberCount:'15000'}}]}};`,ctx);
const result=await ctx.subject.growBase({BUCKET:bucket},{categories:['Cantores'],pages:1,more:true});
assert.equal(result.added,1,'A category with 200 channels must continue growing');
assert.equal(result.baseSize,201);
assert.equal(result.targetPerCategory,2000);
const state=[...records.entries()].find(([k])=>k.startsWith('base-progress/'));
assert.equal(state[1].pageToken,'page-two');
records.set(state[0],{queryIndex:1,pageToken:'',pageInQuery:0});
await ctx.subject.growBase({BUCKET:bucket},{categories:['Cantores'],pages:1,more:true});
assert.equal(ctx.params.at(-2).type,'channel','Discovery alternates videos and channels');
records.set(state[0],{queryIndex:0,pageToken:'page-eight',pageInQuery:7});
await ctx.subject.growBase({BUCKET:bucket},{categories:['Cantores'],pages:1,more:true});
assert.equal(records.get(state[0]).pageToken,'page-two','Pagination continues beyond the old three-page stop');
const prefix='<a href="https://instagram.com/teste/">Perfil</a>';
ctx.fetch=async()=>new Response(new ReadableStream({start(c){c.enqueue(new TextEncoder().encode(prefix));c.enqueue(new Uint8Array(4500001));c.close();}}),{headers:{'Content-Type':'text/html'}});
const page=await ctx.subject.sourceHtml('https://example.org/elenco');
assert.equal(page.truncated,true);
assert.ok(page.html.includes('instagram.com/teste'),'Large pages retain the readable prefix');
await assert.rejects(()=>ctx.subject.sourceHtml('https://127.0.0.1/private'));
console.log('Discovery: 200-channel stop removed; 2,000/category target; 10,000+ subscriber discovery; channel/video variation; deeper pagination; large public pages; private URL guard passed');
