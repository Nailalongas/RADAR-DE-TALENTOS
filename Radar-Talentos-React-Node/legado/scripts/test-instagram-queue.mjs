import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const db=new Map(),bucket={get:async k=>db.has(k)?{json:async()=>structuredClone(db.get(k))}:null,put:async(k,v)=>db.set(k,JSON.parse(v))};
const source=['worker/taxonomy.js','worker/profile-blocks.js','worker/api.js','worker/curation.js','worker/coverage.js'].map(p=>fs.readFileSync(p,'utf8').replace(/export /g,'')).join('\n');
const ctx=vm.createContext({URL,Date,Intl,Map,Set,crypto:globalThis.crypto});ctx.bucket=bucket;
vm.runInContext(source,ctx);
const links=Array.from({length:125},(_,i)=>({username:'perfil'+i,nome:'Artista '+i,categorias:['Cantores'],youtubeChannelId:'UC'+String(i).padStart(22,'0')}));
db.set('links',{links});
vm.runInContext(`readAll=async(b,p)=>p==='ig-profiles/'?(await b.get('indexes/ig-profiles.json'))?.json()||[]:p==='youtube-instagram-links/'?[(await b.get('links')).json()].length?await Promise.all([(await b.get('links')).json()]):[]:[];igRead=async()=>({});reserveInstagram=async(e,n)=>n;globalThis.saved=[];dayRows=async()=>saved;saveDay=async(b,d,rows)=>saved.push(...rows);globalThis.calls=[];igProfile=async(c,username)=>{calls.push(username);if(username==='perfil124')return {username,followers_count:76543,media_count:2};throw Error('A Meta recusou a consulta deste perfil.');};`,ctx);
let run=await vm.runInContext(`collectInstagram({BUCKET:bucket})`,ctx);
assert.equal(run.enqueued,125,'Every stored official link enters the registry');
assert.equal(run.total,125);assert.equal(run.failed.length,120);
run=await vm.runInContext(`collectInstagram({BUCKET:bucket})`,ctx);
assert.equal(ctx.calls.length,125,'Failed profiles must not monopolize the next round');
assert.equal(run.collected,1);assert.equal(run.failed.length,4);assert.equal(run.waitingRetry,120);
const registry=db.get('indexes/ig-profiles.json');
assert.equal(registry.find(p=>p.username==='perfil0').collectionState,'unavailable');
assert.equal(registry.find(p=>p.username==='perfil124').collectionState,'collected');
assert.equal(ctx.saved[0].seguidores,76543);
run=await vm.runInContext(`collectInstagram({BUCKET:bucket})`,ctx);
assert.equal(ctx.calls.length,125,'Successful daily records and deferred retries are preserved');
assert.equal(run.enqueued,0,'Queue registration is idempotent');
console.log('All linked profiles enter collection; refused profiles wait, later profiles advance, successful counts persist');
// Discovery must run even when the daily counting queue remains large.
vm.runInContext(`globalThis.phases=[];discoverInstagram=async()=>{phases.push('discovery');return {added:2};};auditLanguages=async()=>{phases.push('language');return {checked:20};};collectInstagram=async()=>{phases.push('collection');return {remaining:100,results:[{ok:true}]};};`,ctx);
const expanded=await vm.runInContext('syncInstagram({BUCKET:bucket})',ctx);
assert.deepEqual([...ctx.phases],['collection','discovery','language']);
assert.equal(expanded.discovery.added,2);
vm.runInContext(`phases=[];discoverInstagram=async()=>{throw Error('Fonte temporariamente indisponível');};`,ctx);
const recovered=await vm.runInContext('syncInstagram({BUCKET:bucket})',ctx);
assert.deepEqual([...ctx.phases],['collection','language']);
assert.match(recovered.discovery.error,/indisponível/);
console.log('Registered profiles are collected before discovery; discovery failures do not block counting');
